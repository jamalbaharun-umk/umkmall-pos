import { z } from 'zod';
import { Rupiah, validate } from '../common/validation';
import { PRODUCT_TYPES } from '../db/schema';

/** Parses at the boundary: 422 `{ message, errors }` with Indonesian messages (common/validation). */
export const parse = validate;

export const Uuid = z.string().uuid();

const nameOf = (what: string) =>
  z
    .string({ required_error: `Nama ${what} wajib diisi` })
    .trim()
    .min(1, `Nama ${what} wajib diisi`)
    .max(120, 'Maksimal 120 karakter');
const codeOf = (what: string) =>
  z
    .string()
    .trim()
    .min(3, `${what} minimal 3 karakter`)
    .max(64, `${what} maksimal 64 karakter`)
    .regex(/^\S+$/, `${what} tidak boleh berisi spasi`);
const code = codeOf('SKU');

export const CategoryInput = z.object({ name: nameOf('kategori') }).strict();

const barcodes = z
  .array(codeOf('Barcode'))
  .max(20, 'Maksimal 20 barcode')
  .refine(
    (list) => new Set(list).size === list.length,
    'Barcode tidak boleh ganda',
  );

const productFields = {
  categoryId: z
    .string({ required_error: 'Pilih kategori' })
    .uuid('Pilih kategori'),
  name: nameOf('produk'),
  // Blank → generated by the server. Never contains whitespace (Lakasir generated "MIN-ES -0001").
  sku: z.union([code, z.literal('')]).optional(),
  unit: z
    .string()
    .trim()
    .min(1, 'Satuan wajib diisi')
    .max(20, 'Maksimal 20 karakter')
    .optional(),
  costPrice: Rupiah.optional(),
  sellingPrice: z
    .number({
      required_error: 'Harga jual wajib diisi',
      invalid_type_error: 'Harga jual harus berupa angka',
    })
    .int('Harga jual harus bilangan bulat rupiah')
    .positive('Harga jual harus lebih dari 0')
    .max(1_000_000_000_000, 'Harga jual terlalu besar'),
  type: z.enum(PRODUCT_TYPES).optional(),
  isActive: z.boolean().optional(),
  lowStockThreshold: z
    .number({ invalid_type_error: 'Batas stok menipis harus berupa angka' })
    .int('Batas stok menipis harus bilangan bulat')
    .min(0, 'Batas stok menipis tidak boleh negatif')
    .max(1_000_000, 'Batas stok menipis terlalu besar')
    .optional(),
  barcodes: barcodes.optional(),
};

const costNotAboveSelling = (p: {
  costPrice?: number;
  sellingPrice?: number;
}) =>
  p.costPrice === undefined ||
  p.sellingPrice === undefined ||
  p.costPrice <= p.sellingPrice;

export const ProductCreate = z
  .object(productFields)
  .strict()
  .refine(costNotAboveSelling, {
    message: 'Harga modal tidak boleh melebihi harga jual',
    path: ['costPrice'],
  });

// sku on update: a non-blank code (blank would mean "regenerate", which nobody asked for).
export const ProductUpdate = z
  .object({ ...productFields, sku: code })
  .partial()
  .strict();

export const ProductQuery = z.object({
  q: z.string().trim().max(100).optional(),
  categoryId: Uuid.optional(),
  // UMK-1966: only tracked products that are running low (0 < on-hand <= threshold) or out (on-hand 0).
  stock: z.enum(['low', 'out']).optional(),
  page: z.coerce.number().int().min(1).default(1),
  perPage: z.coerce.number().int().min(1).max(100).default(20),
});

export type ProductCreate = z.infer<typeof ProductCreate>;
export type ProductUpdate = z.infer<typeof ProductUpdate>;
export type ProductQuery = z.infer<typeof ProductQuery>;
