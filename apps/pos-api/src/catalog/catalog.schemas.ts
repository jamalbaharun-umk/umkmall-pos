import { UnprocessableEntityException } from '@nestjs/common';
import { z } from 'zod';
import { PRODUCT_TYPES } from '../db/schema';

/** Parses at the boundary; bad input answers 422 with field paths only (no echo of values). */
export function parse<O, I = O>(
  schema: z.ZodType<O, z.ZodTypeDef, I>,
  input: unknown,
): O {
  const result = schema.safeParse(input);
  if (!result.success) {
    throw new UnprocessableEntityException({
      message: 'Data tidak valid',
      fields: result.error.issues.map((i) => i.path.join('.') || '(root)'),
    });
  }
  return result.data;
}

export const Uuid = z.string().uuid();

const name = z.string().trim().min(1).max(120);
// Integer rupiah: no fractions, no negatives, no numeric strings.
const rupiah = z.number().int().nonnegative().max(1_000_000_000_000);
const code = z.string().trim().min(3).max(64).regex(/^\S+$/, 'tanpa spasi');

export const CategoryInput = z.object({ name }).strict();

const barcodes = z
  .array(code)
  .max(20)
  .refine((list) => new Set(list).size === list.length, 'barcode ganda');

const productFields = {
  categoryId: Uuid,
  name,
  // Blank → generated by the server. Never contains whitespace (Lakasir generated "MIN-ES -0001").
  sku: z.union([code, z.literal('')]).optional(),
  unit: z.string().trim().min(1).max(20).optional(),
  costPrice: rupiah.optional(),
  sellingPrice: rupiah,
  type: z.enum(PRODUCT_TYPES).optional(),
  isActive: z.boolean().optional(),
  barcodes: barcodes.optional(),
};

const costNotAboveSelling = (p: {
  costPrice?: number;
  sellingPrice?: number;
}) =>
  p.costPrice === undefined ||
  p.sellingPrice === undefined ||
  p.costPrice <= p.sellingPrice;

export const ProductCreate = z
  .object(productFields)
  .strict()
  .refine(costNotAboveSelling, {
    message: 'harga modal melebihi harga jual',
    path: ['costPrice'],
  });

// sku on update: a non-blank code (blank would mean "regenerate", which nobody asked for).
export const ProductUpdate = z
  .object({ ...productFields, sku: code })
  .partial()
  .strict();

export const ProductQuery = z.object({
  q: z.string().trim().max(100).optional(),
  categoryId: Uuid.optional(),
  page: z.coerce.number().int().min(1).default(1),
  perPage: z.coerce.number().int().min(1).max(100).default(20),
});

export type ProductCreate = z.infer<typeof ProductCreate>;
export type ProductUpdate = z.infer<typeof ProductUpdate>;
export type ProductQuery = z.infer<typeof ProductQuery>;
