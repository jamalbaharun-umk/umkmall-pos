import { z } from 'zod';
import { Rupiah, validate } from '../common/validation';
import { PRODUCT_TYPES } from '../db/schema';

/** Parses at the boundary: 422 `{ message, errors }` with Indonesian messages (common/validation). */
export const parse = validate;

export const Uuid = z.string().uuid();

const nameOf = (what: string) =>
  z
    .string({ required_error: `Nama ${what} wajib diisi` })
    .trim()
    .min(1, `Nama ${what} wajib diisi`)
    .max(120, 'Maksimal 120 karakter');
const codeOf = (what: string) =>
  z
    .string()
    .trim()
    .min(3, `${what} minimal 3 karakter`)
    .max(64, `${what} maksimal 64 karakter`)
    .regex(/^\S+$/, `${what} tidak boleh berisi spasi`);
const code = codeOf('SKU');

export const CategoryInput = z.object({ name: nameOf('kategori') }).strict();

const barcodes = z
  .array(codeOf('Barcode'))
  .max(20, 'Maksimal 20 barcode')
  .refine(
    (list) => new Set(list).size === list.length,
    'Barcode tidak boleh ganda',
  );

const unitPrice = (what: string) =>
  z
    .number({
      required_error: `${what} wajib diisi`,
      invalid_type_error: `${what} harus berupa angka`,
    })
    .int(`${what} harus bilangan bulat rupiah`)
    .positive(`${what} harus lebih dari 0`)
    .max(1_000_000_000_000, `${what} terlalu besar`);

const productFields = {
  categoryId: z
    .string({ required_error: 'Pilih kategori' })
    .uuid('Pilih kategori'),
  name: nameOf('produk'),
  // Blank → generated by the server. Never contains whitespace (Lakasir generated "MIN-ES -0001").
  sku: z.union([code, z.literal('')]).optional(),
  unit: z
    .string()
    .trim()
    .min(1, 'Satuan wajib diisi')
    .max(20, 'Maksimal 20 karakter')
    .optional(),
  costPrice: Rupiah.optional(),
  sellingPrice: z
    .number({
      required_error: 'Harga jual wajib diisi',
      invalid_type_error: 'Harga jual harus berupa angka',
    })
    .int('Harga jual harus bilangan bulat rupiah')
    .positive('Harga jual harus lebih dari 0')
    .max(1_000_000_000_000, 'Harga jual terlalu besar'),
  type: z.enum(PRODUCT_TYPES).optional(),
  isActive: z.boolean().optional(),
  lowStockThreshold: z
    .number({ invalid_type_error: 'Batas stok menipis harus berupa angka' })
    .int('Batas stok menipis harus bilangan bulat')
    .min(0, 'Batas stok menipis tidak boleh negatif')
    .max(1_000_000, 'Batas stok menipis terlalu besar')
    .optional(),
  barcodes: barcodes.optional(),
  // UMK-1985. Each list replaces the stored one when sent. Rules across fields (unique names, tier order,
  // tier against the base price) are checked by the service on the merged product: catalog/pricing.ts.
  units: z
    .array(
      z
        .object({
          name: z
            .string({ required_error: 'Nama satuan wajib diisi' })
            .trim()
            .min(1, 'Nama satuan wajib diisi')
            .max(20, 'Maksimal 20 karakter'),
          unitQty: z
            .number({
              required_error: 'Isi per satuan wajib diisi',
              invalid_type_error: 'Isi per satuan harus berupa angka',
            })
            .int('Isi per satuan harus bilangan bulat')
            .min(2, 'Isi per satuan minimal 2')
            .max(10_000, 'Isi per satuan maksimal 10.000'),
          price: unitPrice('Harga satuan'),
        })
        .strict(),
    )
    .max(10, 'Maksimal 10 satuan')
    .optional(),
  priceTiers: z
    .array(
      z
        .object({
          minQty: z
            .number({
              required_error: 'Jumlah minimal wajib diisi',
              invalid_type_error: 'Jumlah minimal harus berupa angka',
            })
            .int('Jumlah minimal harus bilangan bulat')
            .min(2, 'Jumlah minimal grosir paling sedikit 2')
            .max(1_000_000, 'Jumlah minimal terlalu besar'),
          price: unitPrice('Harga grosir'),
        })
        .strict(),
    )
    .max(10, 'Maksimal 10 tingkat harga grosir')
    .optional(),
};

const costNotAboveSelling = (p: {
  costPrice?: number;
  sellingPrice?: number;
}) =>
  p.costPrice === undefined ||
  p.sellingPrice === undefined ||
  p.costPrice <= p.sellingPrice;

export const ProductCreate = z
  .object(productFields)
  .strict()
  .refine(costNotAboveSelling, {
    message: 'Harga modal tidak boleh melebihi harga jual',
    path: ['costPrice'],
  });

// sku on update: a non-blank code (blank would mean "regenerate", which nobody asked for).
export const ProductUpdate = z
  .object({ ...productFields, sku: code })
  .partial()
  .strict();

/**
 * What UMKMall's agent may send when it creates a product (owner ruling 24 Nov 2026: the agent never changes a price
 * after the fact): one base price and cost, no extra units, no wholesale tiers, no deactivation.
 */
export const AgentProductCreate = z
  .object({
    categoryId: productFields.categoryId,
    name: productFields.name,
    sku: productFields.sku,
    unit: productFields.unit,
    costPrice: productFields.costPrice,
    sellingPrice: productFields.sellingPrice,
    type: productFields.type,
    lowStockThreshold: productFields.lowStockThreshold,
    barcodes: productFields.barcodes,
  })
  .strict()
  .refine(costNotAboveSelling, {
    message: 'Harga modal tidak boleh melebihi harga jual',
    path: ['costPrice'],
  });

export const ProductQuery = z.object({
  q: z.string().trim().max(100).optional(),
  // Exact SKU (UMKMall's HPP import finds its UMK-<ref> product by it).
  sku: z.string().trim().min(1).max(64).optional(),
  categoryId: Uuid.optional(),
  // UMK-1967: line pickers list stock-tracked products only.
  type: z.enum(PRODUCT_TYPES).optional(),
  // UMK-1966: only tracked products that are running low (0 < on-hand <= threshold) or out (on-hand 0).
  stock: z.enum(['low', 'out']).optional(),
  // UMK-2130: products whose cost is still 0 ("Modal belum diisi").
  cost: z.enum(['missing']).optional(),
  page: z.coerce.number().int().min(1).default(1),
  perPage: z.coerce.number().int().min(1).max(100).default(20),
});

/**
 * UMK-2130 "Produk cepat" from the till: name and price, cost optional (owner ruling 2026-11-28: sell first, complete
 * the catalog later). The server puts it in the "Lainnya" category as a `non_stock` product, so it sells at once
 * without a stock-in; a barcode the till just scanned and did not know may come with it.
 */
export const QuickProductCreate = z
  .object({
    name: productFields.name,
    sellingPrice: productFields.sellingPrice,
    costPrice: productFields.costPrice,
    barcode: codeOf('Barcode').optional(),
  })
  .strict()
  .refine(costNotAboveSelling, {
    message: 'Harga modal tidak boleh melebihi harga jual',
    path: ['costPrice'],
  });

export type ProductCreate = z.infer<typeof ProductCreate>;
export type QuickProductCreate = z.infer<typeof QuickProductCreate>;
export type ProductUpdate = z.infer<typeof ProductUpdate>;
export type ProductQuery = z.infer<typeof ProductQuery>;
